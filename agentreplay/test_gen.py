# Path & Safety Helpers
# ---------------------------------------------------------------------------

_PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATED_TESTS_DIR = _PROJECT_ROOT / "generated_tests"


def sanitize_trace_id(trace_id: Any) -> int:
    """Validate and coerce trace ID to a positive integer.

    Prevents directory traversal or path injection.
    """
    if isinstance(trace_id, bool):
        raise TypeError(f"Trace ID must be an integer, got boolean: {trace_id!r}")
    if isinstance(trace_id, int):
        if trace_id <= 0:
            raise ValueError(f"Trace ID must be a positive integer, got: {trace_id}")
        return trace_id
    if isinstance(trace_id, str):
        s = trace_id.strip()
        if not s.isdigit():
            raise ValueError(f"Trace ID must be a numeric integer, got: {trace_id!r}")
        val = int(s)
        if val <= 0:
            raise ValueError(f"Trace ID must be a positive integer, got: {val}")
        return val
    raise TypeError(f"Trace ID must be an integer, got: {type(trace_id).__name__}")


