def generate_test(
    failed_trace_id: Any,
    fixed_trace_id: Any,
    db: Session | None = None,
    output_dir: pathlib.Path | str | None = None,
) -> GeneratedTest:
    """Generate a regression test file and save a GeneratedTest row in the database.

    Parameters
    ----------
    failed_trace_id : int
        ID of the original failed trace.
    fixed_trace_id : int
        ID of the fixed fork trace.
    db : Session, optional
        SQLAlchemy database session.
    output_dir : Path or str, optional
        Target directory for generated test files (defaults to `generated_tests`).
    """
    clean_failed_id = sanitize_trace_id(failed_trace_id)
    clean_fixed_id = sanitize_trace_id(fixed_trace_id)

    session = db or SessionLocal()
    owns_session = db is None

    try:
        failed_trace = session.query(Trace).filter(Trace.id == clean_failed_id).first()
        if not failed_trace:
            raise ValueError(f"Failed trace #{clean_failed_id} not found")

        fixed_trace = session.query(Trace).filter(Trace.id == clean_fixed_id).first()
        if not fixed_trace:
            raise ValueError(f"Fixed trace #{clean_fixed_id} not found")

        # Run diff to inspect divergent invariant
        diff = diff_traces(clean_failed_id, clean_fixed_id, db=session)

        # Extract metadata from trace
        customer_id = "C001"
        amount = 79.50
        item = "Super Gizmo"
        failed_days_old = 12

        if failed_trace.final_output and isinstance(failed_trace.final_output, dict):
            amount = failed_trace.final_output.get("amount", amount)
            if "days_old" in failed_trace.final_output:
                failed_days_old = int(failed_trace.final_output["days_old"])
        else:
            for step in failed_trace.steps:
                if step.state_after and isinstance(step.state_after, dict):
                    if "days_old" in step.state_after:
                        failed_days_old = int(step.state_after["days_old"])
                        break

        # Boundary (8) must be denied; include trace's own days_old and outer boundary (30)
        negative_days = sorted(list({8, failed_days_old, 30}))

        # Generate test code deterministically
        test_code = _TEST_TEMPLATE.format(
            failed_trace_id=clean_failed_id,
            fixed_trace_id=clean_fixed_id,
            agent_name=failed_trace.agent_name,
            customer_id=customer_id,
            amount=amount,
            item=item,
            negative_days=negative_days,
        )

        # Write to file
        target_dir = pathlib.Path(output_dir) if output_dir else _GENERATED_TESTS_DIR
        target_dir.mkdir(parents=True, exist_ok=True)
        file_path = target_dir / f"test_trace_{clean_failed_id}.py"

        file_path.write_text(test_code, encoding="utf-8")

        # Create or update GeneratedTest record
        desc = (
            f"Regression test for Trace #{clean_failed_id} "
            f"(diff against #{clean_fixed_id} diverged at step {diff.first_divergent_step})"
        )
        gen_test = GeneratedTest(
            trace_id=clean_failed_id,
            description=desc,
            test_code=test_code,
            file_path=str(file_path),
            passes_on_fixed=None,
            fails_on_buggy=None,
            fixed_agent_version=fixed_trace.agent_version or "fixed",
            status="pending",
        )
        session.add(gen_test)
        session.commit()
        session.refresh(gen_test)
        return gen_test

    finally:
        if owns_session:
            session.close()


