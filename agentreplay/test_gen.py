"""Phase 4: Deterministic Regression Test Generator.

Turns a failed trace and its verified fix into a pytest regression test,
and validates that the test is useful:
- FAILS on the buggy agent variant
- PASSES on the fixed agent variant
- Catches over-blocking (always-deny agent FAILS positive control)
- Safety: strictly validated integer trace IDs, no exec() in-process.
"""
from __future__ import annotations

import os
import pathlib
import subprocess
import sys
from typing import Any

from sqlalchemy.orm import Session

from .db import SessionLocal
from .diff import diff_traces
from .models import GeneratedTest, Trace

