def validate_test(
    generated_test_id: int,
    db: Session | None = None,
    timeout: int = 30,
) -> GeneratedTest:
    """Run the generated test file via pytest subprocess against buggy and fixed variants.

    Validates:
    - Must FAIL on buggy agent variant
    - Must PASS on fixed agent variant
    Stores results in DB and marks status as 'valid' or 'rejected'.
    """
    session = db or SessionLocal()
    owns_session = db is None

    try:
        gen_test = (
            session.query(GeneratedTest)
            .filter(GeneratedTest.id == generated_test_id)
            .first()
        )
        if not gen_test:
            raise ValueError(f"GeneratedTest #{generated_test_id} not found")

        file_path = pathlib.Path(gen_test.file_path)
        if not file_path.exists():
            raise FileNotFoundError(f"Generated test file not found at {file_path}")

        # Path safety check
        if not file_path.name.startswith("test_trace_"):
            raise ValueError(f"Invalid test file name: {file_path.name}")

        cwd = str(_PROJECT_ROOT)
        base_env = os.environ.copy()
        base_env["PYTHONPATH"] = cwd

        # 1. Run against BUGGY variant (must FAIL)
        env_buggy = base_env.copy()
        env_buggy["AGENTREPLAY_AGENT"] = "demo_agent.variants:buggy_agent"

        cmd = [
            sys.executable,
            "-m",
            "pytest",
            "-o",
            "testpaths=",
            "-c",
            str(_PROJECT_ROOT / "pyproject.toml"),
            str(file_path),
            "-v",
            "--tb=short",
        ]
        proc_buggy = subprocess.run(
            cmd,
            cwd=cwd,
            env=env_buggy,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        fails_on_buggy = proc_buggy.returncode != 0
        buggy_output = proc_buggy.stdout + proc_buggy.stderr

        # 2. Run against FIXED variant (must PASS)
        env_fixed = base_env.copy()
        env_fixed["AGENTREPLAY_AGENT"] = "demo_agent.variants:fixed_agent"

        proc_fixed = subprocess.run(
            cmd,
            cwd=cwd,
            env=env_fixed,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        passes_on_fixed = proc_fixed.returncode == 0
        fixed_output = proc_fixed.stdout + proc_fixed.stderr

        combined_output = (
            f"=== RUN 1: BUGGY VARIANT (expected failure) ===\n"
            f"Exit Code: {proc_buggy.returncode} (Failed: {fails_on_buggy})\n"
            f"{buggy_output}\n\n"
            f"=== RUN 2: FIXED VARIANT (expected pass) ===\n"
            f"Exit Code: {proc_fixed.returncode} (Passed: {passes_on_fixed})\n"
            f"{fixed_output}"
        )

        gen_test.fails_on_buggy = fails_on_buggy
        gen_test.passes_on_fixed = passes_on_fixed
        gen_test.pytest_output = combined_output

        if fails_on_buggy and passes_on_fixed:
            gen_test.status = "valid"
            gen_test.rejection_reason = None
        else:
            gen_test.status = "rejected"
            reasons = []
            if not fails_on_buggy:
                reasons.append("Test did not fail on buggy agent variant")
            if not passes_on_fixed:
                reasons.append("Test did not pass on fixed agent variant")
            gen_test.rejection_reason = "; ".join(reasons)

        session.commit()
        session.refresh(gen_test)
        return gen_test

    finally:
        if owns_session:
            session.close()
